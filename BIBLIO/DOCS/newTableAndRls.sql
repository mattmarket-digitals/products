CREATE TABLE IF NOT EXISTS public."SanteInfo" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    "userMail" text NOT NULL UNIQUE,
    "repJson" jsonb NOT NULL DEFAULT '{}'::jsonb
);

-- Activation de la sécurité RLS
ALTER TABLE public."SanteInfo"
ENABLE ROW LEVEL SECURITY;

-- Suppression des anciennes policies si elles existent
DROP POLICY IF EXISTS "Insertion publique SanteInfo"
ON public."SanteInfo";

DROP POLICY IF EXISTS "Lecture publique SanteInfo"
ON public."SanteInfo";

DROP POLICY IF EXISTS "Modification publique SanteInfo"
ON public."SanteInfo";

-- INSERT : autoriser l'enregistrement d'un formulaire
CREATE POLICY "Insertion publique SanteInfo"
ON public."SanteInfo"
FOR INSERT
TO anon
WITH CHECK (
    length(trim("userMail")) > 0
    AND jsonb_typeof("repJson") = 'object'
);

-- SELECT : autoriser la lecture des fiches
CREATE POLICY "Lecture publique SanteInfo"
ON public."SanteInfo"
FOR SELECT
TO anon
USING (true);

-- UPDATE : autoriser la modification des fiches
CREATE POLICY "Modification publique SanteInfo"
ON public."SanteInfo"
FOR UPDATE
TO anon
USING (
    length(trim("userMail")) > 0
)
WITH CHECK (
    length(trim("userMail")) > 0
    AND jsonb_typeof("repJson") = 'object'
);

-- Droits SQL pour le rôle anon
GRANT INSERT, SELECT, UPDATE
ON public."SanteInfo"
TO anon;

-- Autoriser l'utilisation de la séquence de l'identifiant
GRANT USAGE, SELECT
ON SEQUENCE public."SanteInfo_id_seq"
TO anon;